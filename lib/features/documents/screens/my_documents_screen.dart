import 'package:flutter/material.dart';
import 'package:hrtz_hrms/core/utils/alert_utils.dart';
import 'package:hrtz_hrms/core/utils/url_launcher_helper.dart';
import 'package:provider/provider.dart';
import '../../auth/providers/auth_provider.dart';
import '../provider/document_provider.dart';
import '../../../core/models/document_model.dart';

class MyDocumentsScreen extends StatelessWidget {
  const MyDocumentsScreen({super.key});

  Future<void> _handleDocumentAction(BuildContext context, String url) async {
    if (url.isEmpty) {
      AlertHelper.snackBarError(context, 'Document URL is not available');
      return;
    }

    try {
      await UrlLauncherHelper.launchUrlString(url);
    } catch (e) {
      if (context.mounted) {
        AlertHelper.snackBarError(context, 'Could not open document');
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: Colors.white,
      appBar: AppBar(
        title: const Text('My Documents',
            style: TextStyle(color: Colors.white, fontWeight: FontWeight.bold)),
        backgroundColor: const Color(0xFF26A69A),
        foregroundColor: Colors.white,
        iconTheme: const IconThemeData(color: Colors.white),
        elevation: 0,
      ),
      body: Consumer<DocumentProvider>(
        builder: (context, provider, child) {
          // Show loading only if we have no data at all
          if (provider.isLoading && provider.documents.isEmpty) {
            return const Center(child: CircularProgressIndicator());
          }

          // Show error only if we have no data (even from cache)
          if (provider.errorMessage != null && provider.documents.isEmpty) {
            return Center(
              child: Column(
                mainAxisAlignment: MainAxisAlignment.center,
                children: [
                  const Icon(Icons.error_outline, size: 48, color: Colors.red),
                  const SizedBox(height: 16),
                  Text('Error: ${provider.errorMessage}'),
                  const SizedBox(height: 16),
                  ElevatedButton(
                    onPressed: () {
                      final authProvider =
                          Provider.of<AuthProvider>(context, listen: false);
                      final id =
                          authProvider.userData?['employeeId']?.toString();
                      if (id != null) {
                        provider.refreshDocuments(id);
                      }
                    },
                    child: const Text('Retry'),
                  ),
                ],
              ),
            );
          }

          final documents = provider.documents;

          return RefreshIndicator(
            onRefresh: () async {
              final authProvider =
                  Provider.of<AuthProvider>(context, listen: false);
              final id = authProvider.userData?['employeeId']?.toString();
              if (id != null) {
                await provider.refreshDocuments(id);
              }
            },
            child: SingleChildScrollView(
              physics: const AlwaysScrollableScrollPhysics(),
              child: Padding(
                padding: const EdgeInsets.all(20.0),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    const Text(
                      'My Documents',
                      style: TextStyle(
                        fontSize: 26,
                        fontWeight: FontWeight.bold,
                        color: Color(0xFF0F172A),
                      ),
                    ),
                    const SizedBox(height: 4),
                    Text(
                      'Official documents generated by HR',
                      style: TextStyle(color: Colors.grey[600], fontSize: 14),
                    ),
                    const SizedBox(height: 30),
                    Container(
                      decoration: BoxDecoration(
                        color: Colors.white,
                        borderRadius: BorderRadius.circular(12),
                        border: Border.all(color: Colors.grey.shade200),
                        boxShadow: [
                          BoxShadow(
                            color: Colors.black.withValues(alpha: 0.03),
                            blurRadius: 10,
                            offset: const Offset(0, 4),
                          ),
                        ],
                      ),
                      child: Column(
                        children: [
                          // Header
                          Padding(
                            padding: const EdgeInsets.symmetric(
                                horizontal: 16, vertical: 15),
                            child: Row(
                              children: [
                                Expanded(
                                    flex: 3,
                                    child: Text('Document',
                                        style: _headerStyle)),
                                Expanded(
                                    flex: 2,
                                    child: Center(
                                        child: Text('Status',
                                            style: _headerStyle))),
                                Expanded(
                                    flex: 2,
                                    child: Center(
                                        child: Text('Type',
                                            style: _headerStyle))),
                                Expanded(
                                    flex: 2,
                                    child: Center(
                                        child: Text('Actions',
                                            style: _headerStyle))),
                              ],
                            ),
                          ),
                          const Divider(height: 1),
                          if (documents.isEmpty && !provider.isLoading)
                            const Padding(
                              padding: EdgeInsets.all(40.0),
                              child: Center(child: Text('No documents found')),
                            )
                          else
                            ...documents.map((doc) => Column(
                                  children: [
                                    _buildDocumentRow(context, doc),
                                    const Divider(height: 1),
                                  ],
                                )),
                        ],
                      ),
                    ),
                  ],
                ),
              ),
            ),
          );
        },
      ),
    );
  }

  TextStyle get _headerStyle => const TextStyle(
        fontWeight: FontWeight.bold,
        color: Colors.black,
        fontSize: 14,
      );

  Widget _buildDocumentRow(BuildContext context, Document doc) {
    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 18),
      child: Row(
        children: [
          Expanded(
            flex: 3,
            child: Row(
              children: [
                const Icon(Icons.description_outlined,
                    size: 20, color: Color(0xFF2563EB)),
                const SizedBox(width: 8),
                Expanded(
                  child: Text(
                    doc.name,
                    style: const TextStyle(
                        fontSize: 13,
                        fontWeight: FontWeight.w500,
                        color: Color(0xFF1E293B)),
                  ),
                ),
              ],
            ),
          ),
          Expanded(
            flex: 2,
            child: Center(
              child: Container(
                padding: const EdgeInsets.symmetric(horizontal: 8, vertical: 4),
                decoration: BoxDecoration(
                  color: const Color(0xFFDCFCE7),
                  borderRadius: BorderRadius.circular(12),
                ),
                child: Text(
                  doc.status.toUpperCase(),
                  style: const TextStyle(
                      color: Color(0xFF166534),
                      fontSize: 10,
                      fontWeight: FontWeight.bold),
                ),
              ),
            ),
          ),
          Expanded(
            flex: 2,
            child: Center(
              child: Text(
                doc.type.toUpperCase(),
                style: const TextStyle(fontSize: 12, color: Color(0xFF64748B)),
              ),
            ),
          ),
          Expanded(
            flex: 2,
            child: Row(
              mainAxisAlignment: MainAxisAlignment.center,
              children: [
                InkWell(
                  onTap: () => _handleDocumentAction(context, doc.url),
                  child: const Icon(Icons.remove_red_eye_outlined,
                      size: 20, color: Color(0xFF2563EB)),
                ),
                const SizedBox(width: 12),
                InkWell(
                  onTap: () => _handleDocumentAction(context, doc.url),
                  child: const Icon(Icons.download_outlined,
                      size: 20, color: Color(0xFF166534)),
                ),
              ],
            ),
          ),
        ],
      ),
    );
  }
}
